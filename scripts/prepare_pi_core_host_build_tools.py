"""Prepare/verify the private B40 Darwin-hosted generators. Never execute target code."""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import platform
import re
import resource
import shlex
import shutil
import stat
import subprocess
import sys
import tarfile
import tempfile
import zipfile
from pathlib import Path, PurePosixPath

ROOT = Path(__file__).resolve().parents[1]
LOCK = ROOT / "packaging/pi-core/host-tools-b40/tools.json"
GATE = ROOT / "packaging/pi-core/source-gate-toolchain-v2.json"
WORK = ROOT / ".aragorn/host-preflight/build-b40/tools-work"
PY = Path("/opt/homebrew/Cellar/python@3.12/3.12.13_4/Frameworks/Python.framework/Versions/3.12")
PYBIN = PY / "bin/python3.12"
SITE = Path("py/lib/python3.12/site-packages")
CANON = lambda v: (json.dumps(v, sort_keys=True, separators=(",", ":")) + "\n").encode()


def fail(message):
    raise ValueError(message)


def digest(path):
    h = hashlib.sha256()
    with Path(path).open("rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def relative(value):
    path = PurePosixPath(value)
    if not path.parts or value != str(path) or path.is_absolute() or ".." in path.parts:
        fail("unsafe archive path")
    return Path(*path.parts)


def tree(path, stdlib=False):
    """Content, file mode, relative name and link identity, without following links."""
    rows = []
    for directory, dirs, names in os.walk(path, followlinks=False):
        dirs.sort()
        if stdlib:
            dirs[:] = [n for n in dirs if n not in {"site-packages", "__pycache__"}]
        elif any(n == "__pycache__" for n in dirs):
            fail("unexpected generated bytecode")
        for n in sorted(dirs + names):
            p = Path(directory) / n
            rel = p.relative_to(path).as_posix()
            mode = p.lstat().st_mode
            if stat.S_ISLNK(mode):
                rows.append([rel, "link", os.readlink(p)])
            elif stat.S_ISREG(mode):
                rows.append([rel, stat.S_IMODE(mode), digest(p)])
            elif stat.S_ISDIR(mode) and not stdlib:
                rows.append([rel, "dir"])
            elif not stat.S_ISDIR(mode):
                fail("special file in host tools")
    return hashlib.sha256(CANON(sorted(rows))).hexdigest()


def direct(root, relative_path):
    dest = root / relative(relative_path)
    if dest.resolve(strict=False) != dest or root.resolve() != root:
        fail("symlink in destination")
    return dest


def put(path, data, mode):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("xb") as f:
        f.write(data)
    path.chmod(mode)


def host(lock):
    if (platform.system(), platform.machine(), platform.release()) != tuple(lock["host"]):
        fail("host platform differs")
    for p, expected in lock["host_files"].items():
        if digest(p) != expected:
            fail(f"host file drift: {p}")
    if tree(PY / "lib/python3.12", True) != lock["stdlib_sha256"]:
        fail("Python standard library drift")
    gate = json.loads(GATE.read_bytes())
    for k in ("linker", "linker_library"):
        if digest(gate[k]["path"]) != gate[k]["sha256"]:
            fail("retained ELF linker drift")
    return Path(gate["linker"]["path"])


def host_aliases(lock, dest, lld):
    """Scripts use the finalized absolute prefix; no PATH or ambient dylib fallback."""
    q = lambda p: shlex.quote(str(p))
    prefix = WORK / "sealed"
    real = prefix / "native"
    aliases = {}
    for name in lock["aliases"]:
        exe = real / ("llvm-ar" if name == "llvm-ranlib" else name)
        if name == "llvm-ranlib":
            # LLVM selects ranlib mode by the basename of argv[0].
            exe = real / name
            put(direct(dest, "native/llvm-ranlib"), (dest / "native/llvm-ar").read_bytes(), 0o500)
        aliases[name] = ("export DYLD_LIBRARY_PATH=" + q(prefix / "lib") +
                         "\nunset DYLD_INSERT_LIBRARIES DYLD_FRAMEWORK_PATH\nexec " + q(exe))
        if name == "clang":
            aliases[name] += " -resource-dir=" + q(prefix / "lib/clang/23")
    py = prefix / "py/bin/python3"
    aliases["python3"] = ("unset PYTHONPATH PYTHONHOME PYTHONINSPECT PYTHONSTARTUP\n"
                          "export PYTHONDONTWRITEBYTECODE=1 PYTHONNOUSERSITE=1 PYTHONSAFEPATH=1\n"
                          "export PYTHONPYCACHEPREFIX=" + q(prefix / "cache-disabled" / "pyc") +
                          "\nexec " + q(py) + " -sB")
    aliases["meson"] = aliases["python3"] + " -m mesonbuild.mesonmain"
    aliases["ld.lld"] = "exec " + q(lld) + " -flavor gnu"
    aliases["bpftool"] = "exec " + q(prefix / "bin/python3") + " " + q(Path(__file__).resolve()) + " --bpftool"
    # A *regular file* as a parent guarantees ENOTDIR for every bytecode lookup,
    # unlike a "read-only empty directory" subject to host permission repair.
    put(dest / "cache-disabled", b"Aragorn B40: no Python bytecode namespace.\n", 0o400)
    for name, command in aliases.items():
        put(direct(dest, "bin/" + name), ("#!/bin/sh\n" + command + ' "$@"\n').encode(), 0o500)
    # venv discovery must survive scripts invoking sys.executable directly.
    put(dest / "py/bin/python3", PYBIN.read_bytes(), 0o500)
    put(dest / "py/pyvenv.cfg", ("home = " + str(PYBIN.parent) +
        "\ninclude-system-site-packages = false\nversion = 3.12.13\n").encode(), 0o400)


def checked_archive(path, row):
    if not path.is_file() or path.stat().st_size != row["size"] or digest(path) != row["sha256"]:
        fail(f"package hash mismatch: {path.name}")


def materialize(lock, dest, cache):
    lld = host(lock)
    dest.mkdir(mode=0o700, exist_ok=False)
    for name, row in lock["bottles"].items():
        paths = list(cache.glob("*--" + row["filename"]))
        if len(paths) != 1:
            fail(f"expected one cached Homebrew package: {row['filename']}")
        checked_archive(paths[0], row)
        prefix = name + "/" + row["filename"].split("--")[1].split(".arm64_tahoe")[0] + "/"
        found = set()
        with tarfile.open(paths[0], mode="r|gz") as t:
            for member in t:
                if not member.name.startswith(prefix):
                    continue
                src = member.name[len(prefix):]
                rel = row["members"].get(src)
                if name == "llvm" and src.startswith("lib/clang/23/include/") and member.isfile():
                    rel = src
                if rel is None:
                    continue
                if not member.isfile() or src in found:
                    fail("non-regular or duplicate reviewed bottle member")
                found.add(src)
                mode = 0o500 if rel.startswith(("native/", "private/")) else 0o400
                put(direct(dest, rel), t.extractfile(member).read(), mode)
        if not set(row["members"]) <= found:
            fail(f"absent reviewed members: {name} {set(row['members']) - found}")
    for row in lock["wheels"].values():
        wheel = WORK / "wheels" / row["filename"]
        checked_archive(wheel, row)
        with zipfile.ZipFile(wheel) as z:
            for info in z.infolist():
                if info.is_dir():
                    continue
                source = relative(info.filename)
                if stat.S_ISLNK(info.external_attr >> 16):
                    fail("symlink in wheel")
                # Non-importable wheel install metadata (scripts/data) isn't used.
                if source.parts[0].endswith(".data"):
                    continue
                put(direct(dest, str(SITE / source)), z.read(info), 0o400)
    host_aliases(lock, dest, lld)


def verify_existing():
    """No setup/probes; re-hash bytes actually used, not a mutable receipt."""
    lock = json.loads(LOCK.read_bytes())
    if lock["schema"] != "aragorn/pi-core-host-tools-darwin-arm64/v1":
        fail("wrong host tools lock")
    host(lock)
    p = WORK / "sealed"
    if p.resolve() != p or not p.is_dir() or tree(p) != lock["sealed_sha256"]:
        fail("private host tool tree differs")
    if not stat.S_ISREG((p / "cache-disabled").lstat().st_mode):
        fail("unsafe bytecode namespace")
    bpf = verify_bpf()
    tools = {f.name: {"path": str(f), "sha256": digest(f)} for f in (p / "bin").iterdir()}
    return {"schema": "aragorn/pi-core-host-tools-receipt/v1", "tools": tools,
            "manifest_sha256": digest(LOCK), "sealed_sha256": lock["sealed_sha256"],
            "runner_sha256": digest(__file__), "bpf_input": bpf,
            "scope": "offline-build-host-tools-only"}


ALPINE = WORK / "alpine-host/root"
CLIENT = WORK.parent / "client-work"


def verify_bpf(path=ALPINE):
    # Source file is in the reviewed pipeline closure; no dynamic search for external code.
    from importlib.util import module_from_spec, spec_from_file_location
    source = ROOT / "scripts/prepare_pi_core_host_bpf_inputs.py"
    spec = spec_from_file_location("_aragorn_bpf_inputs", source)
    mod = module_from_spec(spec)
    sys.path.insert(0, str(ROOT))
    try:
        spec.loader.exec_module(mod)
    finally:
        del sys.path[0]
    receipt = mod.verify(path)
    return {"source_sha256": digest(source), "inventory": receipt}


def scratch_owner(tmp):
    if tmp.resolve(strict=True) != tmp or tmp.name != "tmp":
        fail("owned private B40 temporary directory required")
    work = tmp.parent
    if not ((work.parent == CLIENT and re.fullmatch("[0-9a-f]{64}", work.name)) or
            work == WORK / "bpf-host-probe"):
        fail("not a B40 build/provisioning scratch directory")
    for directory in (work, tmp):
        st = directory.lstat()
        if not stat.S_ISDIR(st.st_mode) or st.st_uid != os.getuid() or st.st_mode & 0o077:
            fail("nonprivate B40 scratch")
    return work


def bpf_args(args, work):
    """Only capability discovery and non-kernel, exact owned BPF object generation."""
    if args == ["--version"]:
        return ["--version"], None, None
    if len(args) not in (3, 4) or args[:1] != ["gen"]:
        fail("refused bpftool operation")
    if (args[1], len(args)) not in {("object", 4), ("skeleton", 3)}:
        fail("refused bpftool generation arguments")
    def owned(s):
        p = Path(os.path.abspath(s))
        if p.resolve(strict=False) != p or not p.is_relative_to(work) or p.suffix != ".o":
            fail("refused nonowned BPF object")
        if not re.fullmatch(r"[A-Za-z0-9_][A-Za-z0-9_.-]{0,120}\.o", p.name):
            fail("invalid BPF object name")
        if not p.parent.is_dir() or (work.parent == CLIENT and not p.is_relative_to(work / "build")):
            fail("not a private build object")
        return p
    src = owned(args[-1])
    st = src.lstat()
    if not stat.S_ISREG(st.st_mode) or st.st_nlink != 1 or not 64 <= st.st_size <= 16 << 20:
        fail("invalid BPF object")
    data = src.read_bytes()
    if data[:6] not in (b"\x7fELF\x02\x01", b"\x7fELF\x02\x02"):
        fail("not a BPF ELF object")
    byteorder = "little" if data[5] == 1 else "big"
    if int.from_bytes(data[16:18], byteorder) != 1 or int.from_bytes(data[18:20], byteorder) != 247:
        fail("not a relocatable BPF object")
    # libbpf derives skeleton identifiers from the basename and bpftool greps
    # the original BPF object name. Only the directory may change.
    if args[1] == "skeleton":
        return ["gen", "skeleton", "/input/" + src.name], data, None
    out = owned(args[2])
    if os.path.lexists(out):
        fail("refused to overwrite BPF output")
    return ["gen", "object", "/output/" + out.name, "/input/" + src.name], data, out


def run_bpf(args):
    tmp = Path(os.environ.get("TMPDIR", ""))
    work = scratch_owner(tmp)
    command, data, output = bpf_args(args, work)
    verify_bpf()
    blink = WORK / "sealed/private/blink"
    if digest(blink) != json.loads(LOCK.read_bytes())["blink_sha256"]:
        fail("Blink executable changed")
    with tempfile.TemporaryDirectory(prefix="bpf-gen-", dir=tmp) as d:
        root = Path(d) / "root"
        shutil.copytree(ALPINE, root, symlinks=True)
        verify_bpf(root)
        if data is not None:
            put(root / command[-1].lstrip("/"), data, 0o400)
        if output is not None:
            (root / "output").mkdir(mode=0o700)
        # Blink initializes emulated dev/proc mountpoints. It may not access host
        # devices, network, or any other build artifact. No machine/guest is booted.
        literal = lambda s: "(literal " + json.dumps(str(s)) + ")"
        sb = ('(version 1)(allow default)(deny network*)(deny file-write*)(deny process-fork)'
              '(deny file-read-data (subpath "/Users") (subpath "/Volumes") (subpath "/dev") (subpath "/private"))'
              '(allow file-read-data ' + literal(blink) + ' (subpath ' + json.dumps(str(root)) + '))'
              '(allow file-write-data (literal "/dev/null"))(allow file-write-create ' +
              " ".join(literal(root / n) for n in ("SystemRoot", "dev", "proc")) + ")")
        if output is not None:
            sb += "(allow file-write* " + literal(root / "output" / output.name) + ")"
        def limits():
            resource.setrlimit(resource.RLIMIT_FSIZE, (64 << 20, 64 << 20))
            resource.setrlimit(resource.RLIMIT_CPU, (20, 20))
        with (Path(d) / "stdout").open("w+b") as stdout, (Path(d) / "stderr").open("w+b") as stderr:
            result = subprocess.run(["/usr/bin/sandbox-exec", "-p", sb, str(blink), "-j", "-m",
                                     "-L", "/dev/null", "/usr/sbin/bpftool", *command],
                                    env={"BLINK_PREFIX": str(root), "LC_ALL": "C", "PATH": "/usr/bin:/bin"},
                                    cwd="/", stdin=subprocess.DEVNULL, stdout=stdout, stderr=stderr,
                                    close_fds=True, timeout=25, check=False, preexec_fn=limits)
            if result.returncode:
                stderr.seek(0)
                fail(f"genuine bpftool exited {result.returncode}: {stderr.read(4096)!r}")
            if output is not None:
                produced = root / "output" / output.name
                if produced.is_symlink() or not produced.is_file() or produced.stat().st_size > 64 << 20:
                    fail("invalid generated BPF object")
                put(output, produced.read_bytes(), 0o400)
            stdout.seek(0)
            shutil.copyfileobj(stdout, sys.stdout.buffer)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--prepare", action="store_true")
    parser.add_argument("--bottle-cache", type=Path, default=Path.home() / "Library/Caches/Homebrew/downloads")
    args = parser.parse_args()
    lock = json.loads(LOCK.read_bytes())
    if args.prepare:
        if WORK.resolve() != WORK:
            fail("unsafe build tools work directory")
        materialize(lock, WORK / "sealed", args.bottle_cache)
    print(CANON(verify_existing()).decode(), end="")


if __name__ == "__main__":
    if sys.argv[1:2] == ["--bpftool"]:
        run_bpf(sys.argv[2:])
    else:
        main()
